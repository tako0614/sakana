// 相槌だけのリプライを弾く門。
//
// エージェントの回答へのリプライは「会話の続き」として起動するが、そこに
// 「ありがとう」「草」まで含めると、相槌のたびに system + 直近30件 + 返信の鎖を
// 積み直して 1回 $0.002 が飛ぶ。
//
// 掛けるのはリプライ経路だけ。メンションは明示的な呼び出しなので素通しする
// (`@bot ありがとう` は本人が呼んでいるので答えていい)。
//
// 判定は「相槌だけ」に厳しく寄せてある。落としてはいけないのは「なんで？」
// 「もっと詳しく」のような短い追撃で、これを殺すと会話を続ける機能そのものが死ぬ。
// なので完全一致でしか弾かない。sentence.js の looksLikeSentence は使わない
// (あれは検索クエリ用で6文字未満を全部落とすため、追撃も一緒に死ぬ)。

// 完全一致でのみ使う。`w` や `ok` は語の中にも出るので部分一致は禁物。
const ACKS = new Set([
  'ありがとう', 'ありがとうございます', 'ありがとうございました', 'ありがと', 'あざす', 'あざーす',
  'サンキュー', 'thanks', 'thank you', 'thx', 'ty',
  '了解', 'りょ', 'りょうかい', 'おけ', 'ok', 'okay', 'おｋ',
  'なるほど', 'なるほどね', 'わかった', 'わかりました', 'そうなんだ', 'たしかに', '確かに',
  'lol',
  'すごい', 'つよい', 'いいね', '助かる', '助かった', 'お疲れ', 'おつ', 'おつかれ'
]);

/**
 * 相槌だけの発言か。
 *
 * メンション・カスタム絵文字・チャンネル参照・絵文字・句読点を落として、
 * 残りが空 (スタンプや画像だけのリプライ) か、相槌の語そのものなら true。
 */
export function isBareAck(text) {
  const raw = String(text ?? '').trim();

  // 疑問符が付いていたら追撃。中身が「なるほど？」でも聞き返している。
  if (/[?？]\s*$/.test(raw)) return false;

  const stripped = raw
    .replace(/<a?:\w+:\d+>/g, ' ')                             // カスタム絵文字
    .replace(/<@[!&]?\d+>/g, ' ')                              // メンション
    .replace(/<#\d+>/g, ' ')                                   // チャンネル参照
    .replace(/\p{Extended_Pictographic}[\uFE0F\u200D\p{Emoji_Modifier}]*/gu, ' ')  // 絵文字
    .replace(/[\s。、.!！…]+/g, ' ')                            // 空白と句読点
    .trim();

  // 絵文字・スタンプ・画像だけのリプライ
  if (!stripped) return true;

  // 「wwww」「草草」のような伸ばしも相槌
  if (/^[wｗ]+$/i.test(stripped)) return true;
  if (/^草+$/.test(stripped)) return true;

  return ACKS.has(stripped.toLowerCase());
}
