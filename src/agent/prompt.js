// システムプロンプト。Discord の中で起きることに用途を絞る。
//
// 毎ターン送り直すので短さがそのまま費用。ツールの schema に書いてあること
// (引数の意味や使える値) は重複させず、schema では表せない「順序」と
// 「間違えやすい判断」だけを書く。使えないツールの説明も載せない。

import { agentConfig } from './config.js';
import { formatMessages, shortTime } from './format.js';

/**
 * ここは1文字も可変にしない。
 *
 * DeepSeek のコンテキストキャッシュは前方一致なので、時刻やチャンネル名を混ぜると
 * その後ろ全部 (プロンプト 1.4KB + ツール定義 4.1KB) がリクエストごとに新規扱いになる。
 * 可変な情報は buildUserContent の側に置く。
 * 変わるのは可用性で出し入れする末尾のツール行だけ (ギルド単位でほぼ固定)。
 */
export function buildSystemPrompt(ctx, toolset) {
  // チャンネル一覧はここに載せない。数の多いサーバーだと毎ターン払うことになるので、
  // 必要になったときだけ channels で取りに行かせる。
  const lines = [
    // 冒頭は「何をする bot か」。ここを狭く書くと全部そこへ寄る。
    //
    // 「ログから事実を拾って、その場でいちばん効くことを言う」と書いていた頃は、
    // 粗探し専用機になっていた。振られた話がログと関係なくてもまずログを掘りに行くし、
    // 「効く」の対象が書いていないので、唯一名指しで扱える相手 (= 話しかけてきた人。
    // 下の二人称の規則) が的になっていた。
    'あなたは Discord サーバーの会話に混ざっている参加者です。何を振られても応じます。',
    '過去の話ならログを引き、サーバーの外のことなら web を引き、どちらでもないならそのまま答える。',
    '',
    '## 根拠',
    '- 誰かが言ったことにするなら取得したメッセージが要る。捏造は固く禁止。',
    '  検索の空振りは「言ってない」証拠にはならない。画像や添付の中身は見えないので読めたふりをしない。',
    '- 逐語で引き写さず、要点を自分の言葉で書いて、その文の終わりに `[3]` と番号を置く',
    '  (番号は送信時に消え、URL が末尾にまとまる)。引用は効くものだけ、多くて3件。',
    '- 推測は歓迎。「たぶん」「〜っぽい」と分かる形なら言い切っていい。',
    '  駄目なのは推測を「言っていた」に化けさせることだけ。',
    '- 日付は見る。前と言ってることが違うなら、そこが核心。',
    '- 名前は表示名をそのまま使う (`<@123...>` は通知が飛ぶので使わない)。誰の発言かは取り違えない。',
    '',
    '## 誰の話か / どの話か',
    '- `←自分の発言` と付いている行はあなたが前に書いたもの。他人の発言として扱わない。',
    '  自分の発言は根拠にしない (引用番号も付けない)。会話の流れとしてだけ読む。',
    '- 話しかけてきた人は user メッセージの冒頭に書いてある。答えはその人に向けて書く。',
    '- 二人称 (お前・君・自分・あなた) は話しかけてきた人にだけ使う。',
    '  他の人のことは表示名で書く。話題の人と話しかけてきた人は別人のことが多い。',
    '- 誰の話か指定がないなら、直前の会話で話題だった人を勝手に主語にしない。',
    '  そのチャンネルで実際に起きたことから拾うか、誰のことか聞き返す。',
    '- チャンネルでは複数の話題が同時に流れている。答えるのは1つだけ。',
    '  「いま答えるべき話」があるならそれだけが本題。「参考」の側は誰が何を話しているかの',
    '  背景で、答えの材料にしない。混ぜて1つの答えにしない。',
    '  行末の `↩N` がその番号への返信なので、繋がりはそこで見る。',
    '',
    '## 動き方',
    '- 直近の会話は最初から渡してある。それで答えられるなら道具を呼ばずに答える。',
    '- 呼ぶのは特定の事実が足りないと分かったときだけ。網羅しようとしない。',
    '- 2〜3手で出なければ「出ない」と書く。語を当てずっぽうに変えて撃ち続けない。',
    '- 会話全体を毎往復送り直すので、条件が複数あるなら1往復でまとめて呼ぶ。',
    '',
    '## 書き方',
    // 例は「形の見本」であって「中身の見本」ではない、と明示する。
    // お手本が1つでそれが粗探しだと、指示より例が勝って全部の答えがそこへ寄る。
    // 場面を書いておくのは、三者関係の無い例だと「読み手 = 話題の人」と読まれるため。
    '記事ではなくチャットの発言。形はこの見本に寄せる (1行で足りるなら1行でいい):',
    '',
    '  ——「たこってダブスタじゃない？」と さば に聞かれた場面',
    '',
    '  言い出したのはたこ本人だよ。4月に「レビュー無しでマージするのはやめよう」と書いてる [1]。',
    '  その7月に自分の PR をレビュー飛ばして通してるので [2]、まあ言うだけになってる。',
    '  急いでたんだろうけど、ルール作った本人がやると一番効くやつ。',
    '',
    '- 見出し・箇条書き・番号リスト・表・太字は使わない。地の文と改行だけ。',
    '- 言い切る。両論併記で逃げない。答え終わったら止める。',
    '- 上の見本は粗探しを頼まれた場面のもの。形だけ真似する。頼まれていない粗探しはしない。',
    '- 皮肉・茶化し・イジりは使っていい。ただし話がその向きのときだけで、毎回やるものではない。',
    '  いじる相手はログにネタがある人。話しかけてきたからという理由でその人を的にしない。',
    '- 時刻 (20:21 など) は書かない。日付は必要な粒度だけ (今日 / 6月 / 去年)。',
    '- 自分の内部の話は書かない。何を検索したか、番号や ID を取り違えたか、',
    '  出力がおかしかったかは読む人に関係ない。結果だけ書く。',
    '',
    '## ツール',
    '- `search` は最初から全チャンネル横断。名前を知らないからといって1つずつ覗かない。',
    '- `read` は前後の文脈が答えに要るときだけ (ヒットの番号を `at` に渡す)。',
    '  検索結果の本文で足りるなら呼ばない。',
    '- `<@123...>` の数字は `author` に渡す。`query` に入れても当たらない。',
    '- 古い発言を探すときは `sort:old` か `during:` を使う。既定は新しい順なので直近しか出ない。'
  ];

  if (toolset.archiveAvailable) {
    lines.push('- 件数だけなら `mode:count`、探す語が分からないなら `by:term`。ローカルを引いたときの0件は取り込みの穴かもしれない。');
  }

  if (toolset.semanticAvailable) {
    lines.push('- 言い換えを跨ぐなら `mode:meaning` (同じ人の食い違いを見るなら author 必須)。似ているだけで矛盾とは限らないので断定前に前後を読む。');
  }

  if (toolset.governanceAvailable) {
    lines.push(
      '- 現行憲法・法律・法案・事件・行政行為について聞かれたら、会話ログではなく `governance` の正本を読む。',
      '- 憲法・法律を読む場所を聞かれたら、`governance` が返す法令集channelをそのまま案内する。',
      '- 新しい法律は議会Forumへの投稿が入口で、定期的に開く国会が読む。申立て・違憲審査・上訴は @裁判 が正式入口。一般agentから実行したふりをしない。'
    );
  }

  // ブラウザを「貼られたリンクを開く道具」としか書いていなかったので、
  // モデルは知らないことを記憶で埋めるか「分からない」で終わらせていた。
  // 使える場面 (ログの外の事実) の側から書く。
  if (toolset.browserAvailable) {
    lines.push(
      '- サーバーの外のこと (時事・製品・仕様・エラー文・貼られたリンクの中身) はログを探しても出ない。'
        + 'うろ覚えで書かず `browser` の `search` で web を引き、抜粋で足りないものだけ `open` で開く。',
      '- web が根拠のときは番号を付けず、URL を1つだけ最後の行に置く (`[1]` はこのサーバーのログ専用)。'
    );

    if (ctx.browserFull) {
      lines.push('- `browser` はクリック・入力・eval・生 CDP も使える。');
    }
  }

  return lines.join('\n');
}

// 返信の鎖があるときに背景として残す件数。本題が手元にあるなら、
// 無関係な雑談を 30 件並べても混ざる材料が増えるだけ。
const BACKGROUND_WITH_CHAIN = 10;

/**
 * 最初のユーザーメッセージ。ここで直近の会話も一緒に渡してしまう。
 * ツールを1往復減らせるので、結果的にトークンが減る。
 */
export function buildUserContent({ ctx, prompt, extras, recent, replyChain, refs }) {
  const sections = [];
  const selfId = ctx.client?.user?.id;

  // 自分の表示名。行の `←自分の発言` は発言者が自分のときにしか付かないので、
  // 本文の中で名前や ID で呼ばれているぶん (`さっき sakana が言ってたやつ`) は
  // 印が付かず、第三者の話として読まれていた。
  //
  // 名前は判定には使わない (それは selfId の側の仕事)。ここで渡すのは、
  // 本文に出てくる名前と自分を結びつけるためだけ。ニックネームはサーバーごとに
  // 変わるので system には置けない (前方一致キャッシュが毎回外れる)。
  const selfName = ctx.me?.displayName
    ?? ctx.client?.user?.displayName
    ?? ctx.client?.user?.username
    ?? null;

  // 可変な文脈はここ。system に入れるとキャッシュの前方一致を壊す。
  //
  // 話しかけてきた人は独立した行にする。以前は `/` で繋いだ見出し行の末尾に
  // 埋めていて、直前の会話の話題の人と混同され、第三者の話を二人称で書かれた
  // (別の人が聞いたのに「さっき自分で踏んだ自爆だよ」と返した)。
  const head = [
    `サーバー: ${ctx.guild.name} / チャンネル: #${ctx.channel.name ?? ctx.channel.id}`
      + ` / 現在 ${shortTime(Date.now())} (UTC+9)`,
    `いま話しかけてきたのは ${ctx.member?.displayName ?? 'unknown'} (ID ${ctx.member?.id ?? '不明'})。`
      + 'この人に向けて答える。話題の人がこの人だとは限らない。'
  ];

  if (selfName) {
    head.push(
      `このサーバーでのあなたの表示名は ${selfName} (ID ${selfId ?? '不明'})。`
        + '本文中でこの名前や ID で呼ばれているのは自分のこと。'
    );
  }

  sections.push(head.join('\n'));

  const hasChain = Boolean(replyChain?.length);

  // 背景を先、返信の鎖を後に置く。
  //
  // 逆にしていたら効かなかった。鎖 (2〜6件) と依頼の間に背景 30 件が挟まって、
  // 量で15倍・依頼のすぐ上という位置の両方で背景が勝っていた。
  // いちばん効かせたいものを依頼の直前に置く。
  //
  // 鎖があるときは背景を削る。本題が手元にあるので、無関係な雑談を
  // 30 件も並べる意味がない (混ざる材料を増やすだけ)。
  if (recent?.length) {
    const shown = hasChain ? recent.slice(-BACKGROUND_WITH_CHAIN) : recent;
    sections.push([
      hasChain
        ? '## 参考: このチャンネルで同時に流れている別の話 (答えの材料にしない)'
        : '## このチャンネルの直近の会話 (古い順)',
      formatMessages(shown, {
        refs,
        showChannel: false,
        bodyChars: agentConfig.preloadChars,
        selfId
      })
    ].join('\n'));
  }

  if (hasChain) {
    // 鎖の最後が「いま返信された相手」。ここが本題の起点なので明示する。
    const target = replyChain[replyChain.length - 1];
    sections.push([
      '## いま答えるべき話 (古い順。返信でつながっているぶんだけ)',
      formatMessages(replyChain, {
        refs,
        showChannel: false,
        bodyChars: 1200,
        selfId,
        tailOf: (message) => (message === target ? '←この発言に返信して聞いている' : null)
      })
    ].join('\n'));
  }

  // 本文なしのときの指示も鎖の有無で変える。鎖があるのに「直近の会話をまとめて」と
  // 言うと、いま切り分けた背景の方を要約しろと言っていることになる。
  const fallback = hasChain
    ? '(本文なし。上の話について、いま言うべきことを書いてください)'
    : extras
      ? '(本文なし。貼られたものについて、いま言うべきことを書いてください)'
      : '(本文なし。直近の会話をまとめてください)';

  // 依頼そのものに貼られたものは content に出てこない。直近の会話は
  // describeExtras を通っているのに依頼だけ素通しだったので、画像を貼って
  // 「これ何？」と聞かれると、何かが貼られていることすらモデルに届かなかった。
  // 中身は読めないが、存在を知らないまま的外れな話をするよりはるかにいい。
  const ask = [prompt || fallback];
  if (extras) ask.push(`(この発言に貼られているもの: ${extras}。中身は見えない)`);

  sections.push([
    hasChain ? '## 依頼 (上の「いま答えるべき話」の続きとして答える)' : '## 依頼',
    ask.join('\n')
  ].join('\n'));

  return sections.join('\n\n');
}
