// 自発参加で agent に渡す一言と、「返す価値が無い」の答えの見分け。

/** 呼ばれていない会話に入るときの前置き。依頼の本文の前に付ける。 */
export const AMBIENT_HINT = '(だれにも呼ばれていない。この会話に自分から入る場面。会話の流れを読んで、入ると本当に面白い・役に立つときだけ一言返す。'
  + '上の発言が自分や AI の話題なら本人として答える。答えのない質問や事実・技術の間違いがあれば、それに答えるか正す。'
  + '面白い一言は、記憶やログに材料があるときだけ。人どうしの内輪のやりとり・もう答えが付いている・独り言・割り込むと邪魔になる流れは、'
  + '返す価値が無いので (skip) とだけ書く。迷ったら (skip))';

/**
 * 直前に自分が答えた相手の、続きの発言に入るときの前置き。呼ばれていないが、会話の相手が続けて話しかけている場面。
 * 自分に向けた発言なら普通に答える。人どうしの話に戻った・独り言・相槌だけなら (skip)。
 */
export const CONTINUE_HINT = '(直前にあなたが答えた相手の、続きの発言。名前やメンションは付いていない。あなたに向けた発言 (返事・つっこみ・続きの質問) なら、'
  + '普通に会話の続きとして答える。人どうしの話に戻った・独り言・相槌だけなら (skip) とだけ書く)';

/** (skip) だけの答えか。飾り・句読点・大文字小文字の違いは許す。 */
export function isPassAnswer(text: unknown): boolean {
  return /^[\s(（\[「『]*skip[\s)）\]」』.。!！]*$/i.test(String(text ?? ''));
}
