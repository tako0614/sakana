// 「〇〇に話しかけられたので」を答えの頭から外す仕組みの検証 (npm run check から tsx で呼ぶ)。
import assert from 'node:assert/strict';
import { stripAddressNarration as strip } from '../src/agent/narration.ts';

// 実際に出た答え (2026-10-17)
assert.equal(
  strip('だこに話しかけられたので、わりと名場面なこれを。\n\nevexって名前が本家とバッティングした騒動があった。', 'だこ'),
  'わりと名場面なこれを。\n\nevexって名前が本家とバッティングした騒動があった。'
);

// 呼ばれた側から書く形・呼んだ側から書く形・敬称・@
assert.equal(strip('さばさんに聞かれたから、結論から言うね。AはBより速い。', 'さば'), '結論から言うね。AはBより速い。');
assert.equal(strip('たこが話しかけてきたので、ざっくり答えるよ。要点は3つ。', 'たこ'), 'ざっくり答えるよ。要点は3つ。');
assert.equal(strip('@Tako に呼ばれたので、答えるね。', 'Tako').length > 0, true);
assert.equal(strip('Takoに呼ばれたので、調べたよ。結果は2件。', 'Tako'), '調べたよ。結果は2件。');
// 前置きだけの1文は文ごと外す
assert.equal(strip('だこに話しかけられた。\nevex の始まりは2024年6月。', 'だこ'), 'evex の始まりは2024年6月。');

// 触らないもの: 第三者の事実・依頼者以外の名前・文中の言及・名前なし
assert.equal(strip('たこは運営に呼ばれたので参加した。', 'だこ'), 'たこは運営に呼ばれたので参加した。');
assert.equal(strip('だこは去年、運営に呼ばれたので参加した。', 'だこ'), 'だこは去年、運営に呼ばれたので参加した。');
assert.equal(strip('結論から言うと、だこに話しかけられたので答えた、という話ではない。', 'だこ'),
  '結論から言うと、だこに話しかけられたので答えた、という話ではない。');
assert.equal(strip('だこに話しかけられたので、わりと名場面。', ''), 'だこに話しかけられたので、わりと名場面。');
assert.equal(strip('だこに話しかけられたので、わりと名場面。', undefined), 'だこに話しかけられたので、わりと名場面。');

// 前置きしか無いときは何も消さない (空の返信にしない)
assert.equal(strip('だこに話しかけられたので、', 'だこ'), 'だこに話しかけられたので、');

// 名前に正規表現の記号があっても壊れない
assert.equal(strip('a.b(c)に呼ばれたので、答えるよ。中身はこれ。', 'a.b(c)'), '答えるよ。中身はこれ。');
assert.equal(strip('axb(c)に呼ばれたので、答えるよ。', 'a.b(c)'), 'axb(c)に呼ばれたので、答えるよ。');

console.log('address narration ok (依頼者の名前で始まる経緯の前置きだけ外す / 第三者の事実は触らない)');
