import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const directory=mkdtempSync(join(tmpdir(),'sakana-human-authority-'));
process.env.DATABASE_PATH=join(directory,'main.sqlite');
process.env.ARCHIVE_DB_PATH=join(directory,'archive.sqlite');
process.env.OPENROUTER_API_KEY='check';
const {loadBootstrapDocuments}=await import('../src/governance/config.js');
const db=await import('../src/governance/db.js');
const {draftBill}=await import('../src/governance/llm.js');
const docs=loadBootstrapDocuments({serverName:'Human Authority Test'});
db.bootstrapGovernanceGuild({guildId:'human-authority',enactedBy:'owner',trustedRoleId:'',enforcementMode:'shadow',...docs,
  appealRoleId:'appeal',categoryId:'category',parliamentForumId:'parliament',courtForumId:'court',courtChatChannelId:'court',procedureChannelId:'procedure'});
const constitution=db.getActiveConstitution('human-authority');
const body={title:'人間の権限を指定する法律',summary:'承認者と拒否権者を別々に指定する。',text:docs.laws[0].text,provisions:structuredClone(docs.laws[0].provisions)};
const config=body.provisions.governance.find((entry)=>entry.key==='criminalCaseProcedure').value.states.approval.config;
Object.assign(config,{scope:'designated',users:['11111111111111111'],veto:{scope:'designated',roles:['22222222222222222'],required:1}});
let output=body;
globalThis.fetch=async(url)=>url.endsWith('/endpoints') ? new Response(JSON.stringify({data:{endpoints:[{pricing:{prompt:'0.0000001',completion:'0.0000002'}}]}}),{status:200}) : new Response(JSON.stringify({choices:[{message:{content:JSON.stringify(output)},finish_reason:'stop'}]}),{status:200});
const request={guildId:'human-authority',constitution,activeLaws:[],policy:constitution.policy,
  petition:{title:body.title,summary:'承認者 11111111111111111 と拒否権ロール 22222222222222222 を指定する。'}};
const drafted=await draftBill(request);
assert.deepEqual(drafted.provisions.governance.find((entry)=>entry.key==='criminalCaseProcedure').value.states.approval.config.users,['11111111111111111']);
output=structuredClone(body);
output.provisions.governance.find((entry)=>entry.key==='criminalCaseProcedure').value.states.approval.config.users=['33333333333333333'];
await assert.rejects(()=>draftBill(request),/authority IDs/,'AIが指定されていないIDを発明して権限を与える案を拒否する');
output={...body,text:'11111111111111111 を処罰する。'};
await assert.rejects(()=>draftBill(request),/snowflake IDs/,'権限の指定欄以外では個人を名指しした処罰条項を拒否する');
console.log('check-human-authority: ok (drafting appointments without targeted punishment)');
